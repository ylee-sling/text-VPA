def _ngram_hashes(text: str, n: int) -> set[int]:
    tokens = _TOKEN.findall(text)
    out = set()
    for i in range(len(tokens) - n + 1):
        digest = hashlib.blake2b("\x00".join(tokens[i:i + n]).encode(), digest_size=8).digest()
        out.add(int.from_bytes(digest, "little"))
    return out


class Decontaminator:
    """Word n-gram overlap with evaluation problems. Words are identifiers and numbers, so punctuation,
    whitespace and formatting are ignored, and a shared signature such as ``(numbers: List[int]) -> List[int]``
    is only 5 words. A text is contaminated if it shares any n-gram (default n = 13) with them."""

    def __init__(self, texts: Iterable[str], n: int = 13) -> None:
        if n < 1:
            raise ValueError("n must be >= 1")
        self.n = n
        self.grams: set[int] = set()
        for text in texts:
            self.grams |= _ngram_hashes(text, n)

    def contaminated(self, text: str) -> bool:
        tokens = _TOKEN.findall(text)
        for i in range(len(tokens) - self.n + 1):
            digest = hashlib.blake2b("\x00".join(tokens[i:i + self.n]).encode(), digest_size=8).digest()
            if int.from_bytes(digest, "little") in self.grams:
                return True
        return False


def evaluation_texts(humaneval: str | Path | None = None, mbpp: str | Path | None = None,
                     extra_jsonl: Sequence[str | Path] = ()) -> list[str]:
    """Texts of the evaluation sets to decontaminate against: HumanEval prompt and solution; MBPP description,
    code and tests; ``{"context", "target"}`` JSONL (e.g. MultiPL-E converted)."""
    from text_vpa.data.dataset import _read_jsonl

    texts: list[str] = []
    if humaneval:
        for row in _read_jsonl(humaneval):
            texts += [row["prompt"], row["prompt"] + row["canonical_solution"]]
    if mbpp:
        for row in _read_jsonl(mbpp):
            texts += [row["text"], row["code"], "\n".join(row.get("test_list") or [])]
    for path in extra_jsonl:
        for row in _read_jsonl(path):
            texts += [row.get("context", ""), row.get("target", "")]
    return [t for t in texts if t]


