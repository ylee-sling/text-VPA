@dataclass(frozen=True)
class SourceFile:
    content: str
    license: str | None          # normalised license (lower case; several joined by ',') or None
    origin: str


def _normalise_license(value: Any) -> str | None:
    if value is None:
        return None
    if isinstance(value, (list, tuple)) or (hasattr(value, "tolist") and not isinstance(value, str)):
        items = [str(v).strip().lower() for v in (value.tolist() if hasattr(value, "tolist") else value) if v]
        return ",".join(items) or None
    text = str(value).strip().lower()
    return text or None


def is_permissive(license_value: str | None, allowed: frozenset[str] = PERMISSIVE_LICENSES) -> bool:
    """True when every listed license is in ``allowed`` (a repository under MIT and GPL is not permissive)."""
    if not license_value:
        return False
    return all(item.strip() in allowed for item in license_value.split(","))


def _pick(row: dict, names: Sequence[str]) -> Any:
    for name in names:
        if name in row and row[name] is not None:
            return row[name]
    return None


def _row_to_source(row: dict, fallback_origin: str) -> SourceFile | None:
    content = _pick(row, CONTENT_FIELDS)
    if not isinstance(content, str):
        return None
    origin = _pick(row, ORIGIN_FIELDS)
    return SourceFile(content, _normalise_license(_pick(row, LICENSE_FIELDS)), str(origin or fallback_origin))


def _expand(pattern: str) -> list[str]:
    paths = sorted(glob.glob(pattern)) if glob.has_magic(pattern) else [pattern]
    if not paths or not all(os.path.exists(p) for p in paths):
        raise FileNotFoundError(f"no file matches {pattern!r}")
    return paths


def iter_sources(spec: str, assume_license: str | None = None, batch_rows: int = 1024) -> Iterator[SourceFile]:
    """Files of a source spec: ``dir:PATH`` (``*.py`` recursively), ``jsonl:GLOB`` or ``parquet:GLOB``.

    Rows of JSONL / Parquet need a content field (``content``, ``code``, ``text`` or ``source``) and may carry
    a license field (``license``, ``licenses``, ``max_stars_repo_licenses``, ...). ``assume_license`` labels
    files without one (for a directory of code whose license you know).
    """
    kind, _, value = spec.partition(":")
    if kind == "dir":
        root = Path(value)
        if not root.is_dir():
            raise FileNotFoundError(f"{root} is not a directory")
        for path in sorted(root.rglob("*.py")):
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            yield SourceFile(text, _normalise_license(assume_license), str(path))
    elif kind == "jsonl":
        for path in _expand(value):
            opener = gzip.open if path.endswith(".gz") else open
            with opener(path, "rt", encoding="utf-8") as handle:  # type: ignore[operator]
                for line_no, line in enumerate(handle, 1):
                    if not line.strip():
                        continue
                    source = _row_to_source(json.loads(line), f"{path}:{line_no}")
                    if source is not None:
                        yield _with_license(source, assume_license)
    elif kind == "parquet":
        try:
            import pyarrow.parquet as pq
        except ImportError as exc:                     # pragma: no cover - environment dependent
            raise SystemExit("reading Parquet needs pyarrow: pip install pyarrow") from exc
        for path in _expand(value):
            handle = pq.ParquetFile(path)
            names = set(handle.schema_arrow.names)
            columns = [c for c in (*CONTENT_FIELDS, *LICENSE_FIELDS, *ORIGIN_FIELDS) if c in names]
            if not any(c in names for c in CONTENT_FIELDS):
                raise ValueError(f"{path}: no content column among {CONTENT_FIELDS} (columns: {sorted(names)})")
            row_no = 0
            for batch in handle.iter_batches(batch_size=batch_rows, columns=columns):
                for row in batch.to_pylist():
                    row_no += 1
                    source = _row_to_source(row, f"{path}:{row_no}")
                    if source is not None:
                        yield _with_license(source, assume_license)
    else:
        raise ValueError(f"unknown source spec {spec!r} (dir:PATH, jsonl:GLOB, parquet:GLOB)")


def _with_license(source: SourceFile, assume_license: str | None) -> SourceFile:
    if source.license is None and assume_license:
        return SourceFile(source.content, _normalise_license(assume_license), source.origin)
    return source


def download_hf_parquet(dataset: str, config: str, out_dir: str | Path, split: str = "train",
                        max_files: int | None = None, token: str | None = None) -> list[Path]:
    """Download the Parquet conversion of a Hugging Face dataset split (resumable: finished files are kept).

    Uses the Hub's ``/api/datasets/{dataset}/parquet/{config}/{split}`` listing; ``token`` (or ``HF_TOKEN``)
    is sent for gated datasets. Each file is written to ``*.part`` and renamed when complete.
    """
    token = token or os.environ.get("HF_TOKEN")
    headers = {"User-Agent": "text-vpa-corpus/1"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    listing = f"https://huggingface.co/api/datasets/{dataset}/parquet/{config}/{split}"
    with urllib.request.urlopen(urllib.request.Request(listing, headers=headers), timeout=60) as response:
        urls = json.loads(response.read().decode())
    if not isinstance(urls, list) or not urls:
        raise ValueError(f"no Parquet files listed at {listing}")
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for i, url in enumerate(urls[: max_files or len(urls)]):
        dest = out / f"{dataset.replace('/', '__')}-{config}-{split}-{i:05d}.parquet"
        paths.append(dest)
        if dest.exists() and dest.stat().st_size > 0:
            logger.info("keep %s", dest)
            continue
        part = dest.with_suffix(".part")
        logger.info("download %s -> %s", url, dest)
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=600) as response, \
                open(part, "wb") as handle:
            while chunk := response.read(1 << 22):
                handle.write(chunk)
        part.replace(dest)
    return paths


