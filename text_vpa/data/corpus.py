@dataclass(frozen=True)
class CorpusLimits:
    max_file_chars: int = 1_000_000
    min_doc_chars: int = 20
    max_doc_chars: int = 2_000
    max_function_lines: int = 80
    max_target_chars: int = 4_000
    min_body_statements: int = 1
    max_non_ascii_fraction: float = 0.05
    skip_tests: bool = True


@dataclass(frozen=True)
class FunctionPair:
    context: str
    target: str
    name: str
    key: str                     # dedup key: SHA-1 of the AST without the docstring
    origin: str = ""
    license: str | None = None


def _import_bindings(module: ast.Module) -> dict[str, tuple[str, str]]:
    """Module-level absolute imports: bound name -> ("import", statement) or (module, "name [as alias]")."""
    out: dict[str, tuple[str, str]] = {}
    for node in module.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    out[alias.asname] = ("import", f"import {alias.name} as {alias.asname}")
                else:                                           # "import os.path" binds "os"
                    out[alias.name.split(".")[0]] = ("import", f"import {alias.name}")
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            for alias in node.names:
                if alias.name == "*":
                    continue
                entry = f"{alias.name} as {alias.asname}" if alias.asname else alias.name
                out[alias.asname or alias.name] = (node.module, entry)
    return out


def _import_lines(needed: Sequence[str], bindings: dict[str, tuple[str, str]]) -> list[str]:
    """``import`` statements binding ``needed`` names; ``from`` imports grouped per module; sorted."""
    plain: set[str] = set()
    grouped: dict[str, set[str]] = {}
    for name in needed:
        module, entry = bindings[name]
        if module == "import":
            plain.add(entry)
        else:
            grouped.setdefault(module, set()).add(entry)
    lines = sorted(plain)
    lines += [f"from {module} import {', '.join(sorted(names))}" for module, names in sorted(grouped.items())]
    return lines


def _defined_and_loaded(func: ast.FunctionDef | ast.AsyncFunctionDef) -> tuple[set[str], set[str], bool]:
    """(names bound inside the function, names it reads, uses ``global``)."""
    defined = {func.name}
    loaded: set[str] = set()
    uses_global = False
    for node in ast.walk(func):
        if isinstance(node, ast.Name):
            (loaded if isinstance(node.ctx, ast.Load) else defined).add(node.id)
        elif isinstance(node, ast.arg):
            defined.add(node.arg)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            defined.add(node.name)
        elif isinstance(node, ast.ExceptHandler) and node.name:
            defined.add(node.name)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            for alias in node.names:
                defined.add(alias.asname or alias.name.split(".")[0])
        elif isinstance(node, ast.Global):
            uses_global = True
        elif isinstance(node, ast.MatchAs | ast.MatchStar) and node.name:
            defined.add(node.name)
        elif isinstance(node, ast.MatchMapping) and node.rest:
            defined.add(node.rest)
    return defined, loaded, uses_global


def _trivial_body(body: Sequence[ast.stmt]) -> bool:
    if len(body) != 1:
        return False
    stmt = body[0]
    if isinstance(stmt, ast.Pass):
        return True
    if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant) and stmt.value.value is Ellipsis:
        return True
    if isinstance(stmt, ast.Raise) and stmt.exc is not None:
        exc = stmt.exc.func if isinstance(stmt.exc, ast.Call) else stmt.exc
        return isinstance(exc, ast.Name) and exc.id == "NotImplementedError"
    return False


def _dedup_key(func: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    clone = copy.copy(func)
    clone.body = func.body[1:]                                # without the docstring
    clone.decorator_list = []
    return hashlib.sha1(ast.dump(clone, annotate_fields=False, include_attributes=False).encode()).hexdigest()


def extract_functions(source: str, limits: CorpusLimits | None = None, origin: str = "",
                      license_value: str | None = None) -> tuple[list[FunctionPair], Counter]:
    """Self-contained documented top-level functions of one file, and the counts of what was dropped why."""
    limits = limits or CorpusLimits()
    reasons: Counter = Counter()
    if len(source) > limits.max_file_chars:
        reasons["file_too_large"] += 1
        return [], reasons
    if any(marker in source[:2000].lower() for marker in _GENERATED):
        reasons["file_generated"] += 1
        return [], reasons
    try:
        with warnings.catch_warnings():                       # e.g. invalid escape sequences in old code
            warnings.simplefilter("ignore")
            module = ast.parse(source)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        reasons["file_unparseable"] += 1
        return [], reasons
    lines = source.splitlines()
    bindings = _import_bindings(module)
    out: list[FunctionPair] = []
    for func in module.body:
        if not isinstance(func, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        reason = _check_function(func, limits)
        if reason:
            reasons[reason] += 1
            continue
        doc_node = func.body[0]
        if doc_node.end_lineno is None or func.end_lineno is None or func.body[1].lineno <= doc_node.end_lineno:
            reasons["inline_body"] += 1
            continue
        defined, loaded, uses_global = _defined_and_loaded(func)
        if uses_global:
            reasons["global_state"] += 1
            continue
        free = loaded - defined - BUILTIN_NAMES
        if free - bindings.keys():
            reasons["external_names"] += 1
            continue
        imports = _import_lines(sorted(free), bindings)
        header = "\n".join(imports) + "\n\n\n" if imports else ""
        prompt = "\n".join(line.rstrip() for line in lines[func.lineno - 1: doc_node.end_lineno]) + "\n"
        body = "\n".join(line.rstrip() for line in lines[func.lineno - 1: func.end_lineno]).rstrip() + "\n"
        if body.count("\n") > limits.max_function_lines:
            reasons["too_many_lines"] += 1
            continue
        target = header + body
        if len(target) > limits.max_target_chars:
            reasons["too_long"] += 1
            continue
        if sum(not c.isascii() for c in target) > limits.max_non_ascii_fraction * len(target):
            reasons["non_ascii"] += 1
            continue
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                ast.parse(target)
                ast.parse(header + prompt + "    pass\n")
        except (SyntaxError, ValueError):
            reasons["reassembly"] += 1
            continue
        out.append(FunctionPair(header + prompt, target, func.name, _dedup_key(func), origin, license_value))
    return out, reasons


def _check_function(func: ast.FunctionDef | ast.AsyncFunctionDef, limits: CorpusLimits) -> str | None:
    if func.decorator_list:
        return "decorated"
    if limits.skip_tests and _TEST_NAME.match(func.name):
        return "test_function"
    doc = ast.get_docstring(func, clean=True)
    if not doc:
        return "no_docstring"
    if not limits.min_doc_chars <= len(doc) <= limits.max_doc_chars:
        return "docstring_length"
    body = func.body[1:]
    if len(body) < limits.min_body_statements or _trivial_body(body):
        return "trivial_body"
    return None


