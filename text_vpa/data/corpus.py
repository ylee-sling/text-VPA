@dataclass
class CorpusStats:
    files_seen: int = 0
    files_license_rejected: int = 0
    files_used: int = 0
    functions_extracted: int = 0
    duplicates: int = 0
    contaminated: int = 0
    train: int = 0
    val: int = 0
    documented: int = 0                      # kept functions (train + val) with a docstring
    methods: int = 0                         # kept functions that are methods of a class
    dropped: dict[str, int] = field(default_factory=dict)
    licenses: dict[str, int] = field(default_factory=dict)


_STATE: dict[str, Any] = {}                 # per worker process: limits and decontaminator


def _init_worker(limits: CorpusLimits, decontaminator: Decontaminator | None) -> None:
    _STATE["limits"], _STATE["decontaminator"] = limits, decontaminator


def _process_chunk(files: list[SourceFile]) -> tuple[list[FunctionPair], Counter, int]:
    limits, decon = _STATE["limits"], _STATE["decontaminator"]
    pairs: list[FunctionPair] = []
    reasons: Counter = Counter()
    contaminated = 0
    for f in files:
        found, why = extract_functions(f.content, limits, f.origin, f.license)
        reasons.update(why)
        for pair in found:
            if decon is not None and (decon.contaminated(pair.target) or decon.contaminated(pair.context)):
                contaminated += 1
            else:
                pairs.append(pair)
    return pairs, reasons, contaminated


class _ShardWriter:
    def __init__(self, out_dir: Path, prefix: str, shard_size: int | None) -> None:
        self.out_dir, self.prefix, self.shard_size = out_dir, prefix, shard_size
        self.index, self.count, self.handle = 0, 0, None
        self.paths: list[Path] = []

    def write(self, row: dict) -> None:
        if self.handle is None or (self.shard_size and self.count >= self.shard_size):
            self.close()
            name = f"{self.prefix}-{self.index:05d}.jsonl.gz" if self.shard_size else f"{self.prefix}.jsonl.gz"
            path = self.out_dir / name
            self.paths.append(path)
            self.handle = gzip.open(path.with_suffix(".tmp"), "wt", encoding="utf-8")
            self.index, self.count = self.index + 1, 0
        self.handle.write(json.dumps(row, ensure_ascii=False) + "\n")
        self.count += 1

    def close(self) -> None:
        if self.handle is not None:
            self.handle.close()
            self.paths[-1].with_suffix(".tmp").replace(self.paths[-1])
            self.handle = None


def _chunks(items: Iterable[SourceFile], size: int) -> Iterator[list[SourceFile]]:
    chunk: list[SourceFile] = []
    for item in items:
        chunk.append(item)
        if len(chunk) == size:
            yield chunk
            chunk = []
    if chunk:
        yield chunk


def build_corpus(sources: Sequence[str], out_dir: str | Path, eval_texts: Sequence[str] = (),
                 licenses: frozenset[str] = PERMISSIVE_LICENSES, allow_unknown_license: bool = False,
                 assume_license: str | None = None, limits: CorpusLimits | None = None, ngram: int = 13,
                 max_functions: int | None = None, val_fraction: float = 0.005, shard_size: int = 100_000,
                 workers: int = 1, chunk_files: int = 256, prefer_documented: bool = False) -> CorpusStats:
    """Run the pipeline of the module docstring; returns the statistics (also written to ``stats.json``).

    The output does not depend on ``workers``: files are processed in order and deduplication keeps the first
    occurrence. ``val_fraction`` of the functions (chosen by their dedup key) go to ``val.jsonl.gz``.
    ``max_functions`` stops the build once that many functions are kept; with ``prefer_documented``
    undocumented functions are held back and only fill what the documented ones leave of ``max_functions``
    (all sources are read unless the documented functions alone reach it).
    """
    if not 0.0 <= val_fraction < 1.0:
        raise ValueError("val_fraction must lie in [0, 1)")
    limits = limits or CorpusLimits()
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stats = CorpusStats()
    decon = Decontaminator(eval_texts, ngram) if eval_texts else None
    if decon is None:
        logger.warning("no evaluation texts: the corpus is NOT decontaminated")
    licenses_seen: Counter = Counter()
    dropped: Counter = Counter()

    def admitted() -> Iterator[SourceFile]:
        for spec in sources:
            for f in iter_sources(spec, assume_license):
                stats.files_seen += 1
                licenses_seen[f.license or "unknown"] += 1
                if is_permissive(f.license, licenses) or (allow_unknown_license and f.license is None):
                    stats.files_used += 1
                    yield f
                else:
                    stats.files_license_rejected += 1

    train = _ShardWriter(out, "train", shard_size)
    val = _ShardWriter(out, "val", None)
    reserve_path = out / "reserve.jsonl.gz.tmp"               # undocumented functions held back
    reserve = gzip.open(reserve_path, "wt", encoding="utf-8") if prefer_documented and max_functions else None
    seen: set[str] = set()
    threshold = int(val_fraction * 2**32)

    def keep(row: dict, to_val: bool) -> None:
        stats.documented += row["documented"]
        stats.methods += row["method"]
        if to_val:
            val.write(row)
            stats.val += 1
        else:
            train.write(row)
            stats.train += 1

    def full() -> bool:
        return max_functions is not None and stats.train + stats.val >= max_functions
    if workers > 1:
        pool = multiprocessing.get_context("spawn").Pool(workers, initializer=_init_worker, initargs=(limits, decon))
        results = pool.imap(_process_chunk, _chunks(admitted(), chunk_files))
    else:
        pool = None
        _init_worker(limits, decon)
        results = map(_process_chunk, _chunks(admitted(), chunk_files))
    try:
        for pairs, reasons, contaminated in results:
            dropped.update(reasons)
            stats.contaminated += contaminated
            stats.functions_extracted += len(pairs) + contaminated
            for pair in pairs:
                if pair.key in seen:
                    stats.duplicates += 1
                    continue
                seen.add(pair.key)
                row = {"context": pair.context, "target": pair.target, "language": "python",
                       "task_id": f"{pair.origin}::{pair.name}", "license": pair.license, "origin": pair.origin,
                       "documented": pair.documented, "method": pair.method}
                to_val = int(pair.key[:8], 16) < threshold
                if reserve is not None and not pair.documented:
                    reserve.write(json.dumps({"val": to_val, "row": row}, ensure_ascii=False) + "\n")
                    continue
                keep(row, to_val)
                if full():
                    break
            if full():
                break
        if reserve is not None:                               # fill up with the undocumented functions
            reserve.close()
            reserve = None
            with gzip.open(reserve_path, "rt", encoding="utf-8") as handle:
                for line in handle:
                    if full():
                        break
                    held = json.loads(line)
                    keep(held["row"], held["val"])
    finally:
        if pool is not None:
            pool.terminate()
            pool.join()
        if reserve is not None:
            reserve.close()
        reserve_path.unlink(missing_ok=True)
        train.close()
        val.close()
    stats.dropped = dict(sorted(dropped.items()))
    stats.licenses = dict(licenses_seen.most_common())
    summary = asdict(stats) | {"sources": list(sources), "ngram": ngram, "decontaminated": decon is not None,
                               "limits": asdict(limits), "train_files": [p.name for p in train.paths],
                               "allowed_licenses": sorted(licenses), "max_functions": max_functions,
                               "prefer_documented": prefer_documented}
    (out / "stats.json").write_text(json.dumps(summary, indent=2))
    return stats


