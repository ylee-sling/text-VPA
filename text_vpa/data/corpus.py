@dataclass(frozen=True)
class SourceFile:
    content: str
    license: str | None          # normalised license (lower case; several joined by ',') or None
    origin: str


def _normalise_license(value: Any) -> str | None:
    if value is None:
        return None
    if isinstance(value, (list, tuple)) or (hasattr(value, "tolist") and not isinstance(value, str)):
        items = [str(v).strip().lower() for v in (value.tolist() if hasattr(value, "tolist") else value) if v]
        return ",".join(items) or None
    text = str(value).strip().lower()
    return text or None


def is_permissive(license_value: str | None, allowed: frozenset[str] = PERMISSIVE_LICENSES) -> bool:
    """True when every listed license is in ``allowed`` (a repository under MIT and GPL is not permissive)."""
    if not license_value:
        return False
    return all(item.strip() in allowed for item in license_value.split(","))


def _pick(row: dict, names: Sequence[str]) -> Any:
    for name in names:
        if name in row and row[name] is not None:
            return row[name]
    return None


def _row_to_source(row: dict, fallback_origin: str) -> SourceFile | None:
    content = _pick(row, CONTENT_FIELDS)
    if not isinstance(content, str):
        return None
    origin = None
    for repo, path in (("repo_name", "path"), ("max_stars_repo_name", "max_stars_repo_path")):
        if row.get(repo) and row.get(path):                    # "owner/repo/dir/file.py": unique across repositories
            origin = f"{row[repo]}/{row[path]}"
            break
    origin = origin or _pick(row, ORIGIN_FIELDS)
    return SourceFile(content, _normalise_license(_pick(row, LICENSE_FIELDS)), str(origin or fallback_origin))


def _expand(pattern: str) -> list[str]:
    paths = sorted(glob.glob(pattern)) if glob.has_magic(pattern) else [pattern]
    if not paths or not all(os.path.exists(p) for p in paths):
        raise FileNotFoundError(f"no file matches {pattern!r}")
    return paths


def iter_sources(spec: str, assume_license: str | None = None, batch_rows: int = 1024) -> Iterator[SourceFile]:
    """Files of a source spec: ``dir:PATH`` (``*.py`` recursively), ``jsonl:GLOB`` or ``parquet:GLOB``.

    Rows of JSONL / Parquet need a content field (``content``, ``code``, ``text`` or ``source``) and may carry
    a license field (``license``, ``licenses``, ``max_stars_repo_licenses``, ...). ``assume_license`` labels
    files without one (for a directory of code whose license you know).
    """
    kind, _, value = spec.partition(":")
    if kind == "dir":
        root = Path(value)
        if not root.is_dir():
            raise FileNotFoundError(f"{root} is not a directory")
        for path in sorted(root.rglob("*.py")):
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            yield SourceFile(text, _normalise_license(assume_license), str(path))
    elif kind == "jsonl":
        for path in _expand(value):
            opener = gzip.open if path.endswith(".gz") else open
            with opener(path, "rt", encoding="utf-8") as handle:  # type: ignore[operator]
                for line_no, line in enumerate(handle, 1):
                    if not line.strip():
                        continue
                    source = _row_to_source(json.loads(line), f"{path}:{line_no}")
                    if source is not None:
                        yield _with_license(source, assume_license)
    elif kind == "parquet":
        try:
            import pyarrow.parquet as pq
        except ImportError as exc:                     # pragma: no cover - environment dependent
            raise SystemExit("reading Parquet needs pyarrow: pip install pyarrow") from exc
        for path in _expand(value):
            handle = pq.ParquetFile(path)
            names = set(handle.schema_arrow.names)
            columns = [c for c in (*CONTENT_FIELDS, *LICENSE_FIELDS, *ORIGIN_FIELDS) if c in names]
            if not any(c in names for c in CONTENT_FIELDS):
                raise ValueError(f"{path}: no content column among {CONTENT_FIELDS} (columns: {sorted(names)})")
            row_no = 0
            for batch in handle.iter_batches(batch_size=batch_rows, columns=columns):
                for row in batch.to_pylist():
                    row_no += 1
                    source = _row_to_source(row, f"{path}:{row_no}")
                    if source is not None:
                        yield _with_license(source, assume_license)
    else:
        raise ValueError(f"unknown source spec {spec!r} (dir:PATH, jsonl:GLOB, parquet:GLOB)")


def _with_license(source: SourceFile, assume_license: str | None) -> SourceFile:
    if source.license is None and assume_license:
        return SourceFile(source.content, _normalise_license(assume_license), source.origin)
    return source


def _retry(action, what: str, attempts: int, base_delay: float):
    """Run ``action`` up to ``attempts`` times with exponential backoff; HTTP 4xx (except 429) fail at once."""
    for attempt in range(1, attempts + 1):
        try:
            return action()
        except urllib.error.HTTPError as exc:
            if 400 <= exc.code < 500 and exc.code != 429:
                raise
            error: Exception = exc
        except (OSError, http.client.HTTPException, ValueError) as exc:
            error = exc
        if attempt == attempts:
            raise RuntimeError(f"{what} failed after {attempts} attempts: {error}") from error
        delay = min(60.0, base_delay * 2 ** (attempt - 1))
        logger.warning("%s failed (%s); retry %d/%d in %.0f s", what, error, attempt, attempts - 1, delay)
        time.sleep(delay)
    raise AssertionError("unreachable")


_PARQUET_REVISION = urllib.parse.quote("refs/convert/parquet", safe="")
_NEXT_LINK = re.compile(r'<([^>]+)>\s*;\s*rel="next"')


def _get_json(url: str, headers: dict[str, str]) -> tuple[Any, str | None]:
    """GET ``url`` as JSON; also returns the ``rel="next"`` URL of a paginated Hub listing (or None)."""
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as response:
        body = json.loads(response.read().decode())
        header = getattr(response, "headers", None)
        link = header.get("Link") if header is not None else None
    match = _NEXT_LINK.search(link or "")
    return body, match.group(1) if match else None


def parquet_tree_urls(dataset: str, config: str, split: str = "train", headers: dict[str, str] | None = None,
                      attempts: int = 6, base_delay: float = 5.0, max_pages: int = 100) -> list[str]:
    """Download URLs of a split's files in the dataset's Parquet export (the ``refs/convert/parquet`` branch).

    The fallback when the ``/parquet`` listing has none: exports of large datasets are partial and have been
    stored under ``{config}/partial-{split}/`` and ``{config}/partial/{split}/`` as well as ``{config}/{split}/``.
    Files are returned in path (shard) order; an unknown dataset or config gives an empty list.
    """
    headers = dict(headers or {"User-Agent": "text-vpa-corpus/1"})
    folders = {f"{config}/{split}", f"{config}/partial-{split}", f"{config}/partial/{split}"}
    url = (f"https://huggingface.co/api/datasets/{dataset}/tree/{_PARQUET_REVISION}/"
           f"{urllib.parse.quote(config)}?recursive=true")
    paths = [str(entry["path"]) for entry in _tree_entries(url, headers, attempts, base_delay, max_pages)
             if str(entry["path"]).endswith(".parquet") and str(entry["path"]).rsplit("/", 1)[0] in folders]
    return [f"https://huggingface.co/datasets/{dataset}/resolve/{_PARQUET_REVISION}/{urllib.parse.quote(p)}"
            for p in sorted(paths)]


def _tree_entries(url: str, headers: dict[str, str], attempts: int, base_delay: float,
                  max_pages: int) -> list[dict]:
    """File entries (``{"type": "file", "path", "size", ...}``) of a paginated Hub tree listing; [] on 404."""
    files: list[dict] = []
    next_url: str | None = url
    for _ in range(max_pages):
        if next_url is None:
            break
        page_url = next_url
        try:
            entries, next_url = _retry(lambda page_url=page_url: _get_json(page_url, headers), f"tree {page_url}",
                                       attempts, base_delay)
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                return []
            raise
        files += [e for e in (entries if isinstance(entries, list) else [])
                  if isinstance(e, dict) and e.get("type") == "file" and e.get("path")]
    return files


def download_hf_parquet(dataset: str, config: str, out_dir: str | Path, split: str = "train",
                        max_files: int | None = None, token: str | None = None, attempts: int = 6,
                        base_delay: float = 5.0) -> list[Path]:
    """Download the Parquet conversion of a Hugging Face dataset split (resumable: finished files are kept).

    Uses the Hub's ``/api/datasets/{dataset}/parquet/{config}/{split}`` listing and, when that lists no files
    (404 or empty), the files of the Parquet export's tree (``parquet_tree_urls``). ``token`` (or ``HF_TOKEN``)
    is sent for gated datasets. Each file is written to ``*.part``, checked against the server's
    Content-Length, and renamed when complete; network errors are retried with exponential backoff.
    """
    token = token or os.environ.get("HF_TOKEN")
    headers = {"User-Agent": "text-vpa-corpus/1"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    listing = f"https://huggingface.co/api/datasets/{dataset}/parquet/{config}/{split}"
    try:
        urls, _ = _retry(lambda: _get_json(listing, headers), f"listing {listing}", attempts, base_delay)
    except urllib.error.HTTPError as exc:
        if exc.code != 404:
            raise
        urls = None
    if not isinstance(urls, list) or not urls:
        urls = parquet_tree_urls(dataset, config, split, headers, attempts, base_delay)
        if not urls:
            raise ValueError(f"no Parquet files for {dataset} ({config}/{split}): none listed at {listing} "
                             "nor in the refs/convert/parquet tree")
        logger.info("%s lists no files; using the %d file(s) of the Parquet export's tree", listing, len(urls))
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for i, url in enumerate(urls[: max_files or len(urls)]):
        dest = out / f"{dataset.replace('/', '__')}-{config}-{split}-{i:05d}.parquet"
        paths.append(dest)
        if dest.exists() and dest.stat().st_size > 0:
            logger.info("keep %s", dest)
            continue
        part = dest.with_suffix(".part")

        def fetch_file(url: str = url, part: Path = part) -> None:
            with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=600) as response, \
                    open(part, "wb") as handle:
                header = getattr(response, "headers", None)
                expected = header.get("Content-Length") if header is not None else None
                written = 0
                while chunk := response.read(1 << 22):
                    handle.write(chunk)
                    written += len(chunk)
            if expected is not None and written != int(expected):
                raise ValueError(f"truncated download: {written} of {expected} bytes")

        logger.info("download %s -> %s", url, dest)
        _retry(fetch_file, f"download {url}", attempts, base_delay)
        part.replace(dest)
    return paths


