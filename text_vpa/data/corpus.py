PERMISSIVE_LICENSES = frozenset({
    "mit", "mit-0", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "bsd-3-clause-clear", "0bsd", "isc",
    "unlicense", "cc0-1.0", "zlib", "bsl-1.0", "psf-2.0", "python-2.0", "wtfpl", "upl-1.0", "x11",
})
CONTENT_FIELDS = ("content", "code", "text", "source")
LICENSE_FIELDS = ("license", "licenses", "max_stars_repo_licenses", "detected_licenses", "license_type")
ORIGIN_FIELDS = ("path", "max_stars_repo_path", "repo_name", "max_stars_repo_name", "id")
BUILTIN_NAMES = frozenset(dir(builtins)) | {"__name__", "__file__", "__doc__", "__debug__", "__class__"}
_GENERATED = ("auto-generated", "autogenerated", "automatically generated", "do not edit", "generated by")
_TEST_NAME = re.compile(r"_?test(_|[A-Z0-9]|$)")          # test, test_x, testFoo, _test_x; not "testable"
_TOKEN = re.compile(r"[A-Za-z_][A-Za-z0-9_]*|\d+")      # words: identifiers and numbers (no punctuation)


